const byValue = new Map<string, UiPack>();
for (const pack of UI_PACKS) {
  for (const value of Object.values(pack)) {
    if (value && !byValue.has(value)) byValue.set(value, pack);
  }
}

export function uiText(locale: Locale, value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const pack = byValue.get(trimmed);
  if (!pack) return value;
  const next = pack[locale] ?? pack.fr;
  return value.replace(trimmed, next);
}

export function uiPick(locale: Locale, fr: string, ar: string, de?: string, en?: string): string {
  if (locale === "ar") return ar;
  if (locale === "de") return de ?? uiText("de", fr);
  if (locale === "en") return en ?? uiText("en", fr);
  return fr;
}
